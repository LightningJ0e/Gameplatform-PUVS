# Structure of this Db is: "<name>" : {"username":"<name>", "password":"<password>", "gamesplayed": <playedGamesAmmount>, "gamesWon": <wonGameAmmount>}
# This structure is generated by the fake_db access in the register method --> user.model_dump()
fake_db: Dict[str, dict] = {}

#Datastruct for a User. Basemodel automatically checks if the parameters are the set type (on creation)
#TODO we should probably hash the passwords and not keep them in plaintext...
class User(BaseModel):
    username: str
    password: str
    gamesPlayed: int = 0
    gamesWon: int = 0

#register new users
@app.post("/register")
def register(user: User):
    if user.username in fake_db:
        raise HTTPException(status_code=400, detail="Username already in use.")
    fake_db[user.username] = user.model_dump()
    return {"message": f"User {user.username} registered successfully"}

#login function for existing users
